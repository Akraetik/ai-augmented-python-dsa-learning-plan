"""Write the LeetCode 150 unlock lists into the course.

    python tools/build_unlocks.py          # rebuild everything
    python tools/build_unlocks.py --check  # exit 1 if any file is out of date

It writes:
  * a "LeetCode 150 you can now solve" block at the end of every lesson
  * a "LeetCode 150 in this section" block in each section README (above the mastery gate)
  * a progress block in the main README
  * sections/24-leetcode-150-checklist/README.md and checklist.csv

Blocks sit between <!-- LC150:START --> and <!-- LC150:END -->. Re-running replaces them.
Data lives in tools/leetcode150.py. Change the data, never the generated blocks.
"""
import csv
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import leetcode150 as L  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START = "<!-- LC150:START -->"
END = "<!-- LC150:END -->"
NOTE = "*Generated by `tools/build_unlocks.py` from `tools/leetcode150.py`. Edit the data file, not this block.*"
CHECKLIST_DIR = "sections/24-leetcode-150-checklist"
DIFF = {"E": "Easy", "M": "Medium", "H": "Hard"}

P = L.by_number()


# ---------------------------------------------------------------- helpers

def lesson_files():
    """[(lesson_id, section, path)] for every lesson in the built sections, in course order."""
    out = []
    for sec, d in L.SECTION_DIRS.items():
        ldir = os.path.join(ROOT, "sections", d, "lessons")
        for name in sorted(os.listdir(ldir)):
            m = re.match(r"(\d+\.\d+)-.*\.md$", name)
            if m:
                out.append((m.group(1), sec, os.path.join(ldir, name)))
    out.sort(key=lambda t: L.lesson_order(t[0]))
    return out


def section_of(unlock):
    return unlock.split(".")[0].zfill(2)


def stamp_label(unlock):
    if "." in unlock:
        return f"Lesson {unlock}"
    return f"Section {unlock} · {L.SECTION_NAMES[unlock]}"


def rel(from_dir, repo_path):
    return os.path.relpath(os.path.join(ROOT, repo_path), from_dir).replace(os.sep, "/")


def link(n):
    p = P[n]
    return f"[{p[1]}]({L.url(p[2])})"


def unlocked_by(unlock):
    """Problem numbers whose stamp is exactly this lesson/section, in a stable order."""
    nums = [p[0] for p in L.PROBLEMS if L.unlock_of(p[0]) == unlock]
    return sorted(nums, key=lambda n: (n not in L.LABS, L.PROBLEMS.index(P[n])))


def total_through(unlock):
    key = L.lesson_order(unlock)
    return sum(1 for p in L.PROBLEMS if L.lesson_order(L.unlock_of(p[0])) <= key)


def revisits_in(lesson_id):
    """Labs in this lesson for problems first unlocked earlier (a second, better pass)."""
    out = []
    for n, labs in L.LABS.items():
        for lesson, path in (labs if n in L.EARLY else labs[1:]):
            if lesson == lesson_id:
                out.append((n, path))
    return out


def all_stamps():
    """Every distinct stamp in course order."""
    return sorted({L.unlock_of(p[0]) for p in L.PROBLEMS}, key=L.lesson_order)


def replace_block(text, block, before_heading=None):
    """Swap an existing block, or insert a new one (above a heading, else at the end)."""
    block = f"{START}\n{block.strip()}\n{END}"
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _m: block, text, count=1)
    if before_heading:
        m = re.search(r"^" + re.escape(before_heading) + r"\s*$", text, re.M)
        if m:
            return text[:m.start()] + block + "\n\n" + text[m.start():]
    return text.rstrip("\n") + "\n\n---\n\n" + block + "\n"


# ---------------------------------------------------------------- lesson blocks

def lesson_block(lesson_id, lesson_dir, next_stamp):
    new = unlocked_by(lesson_id)
    early = [n for n in new if n in L.EARLY]
    labs = [n for n in new if n in L.LABS and n not in L.EARLY]
    revisit = revisits_in(lesson_id)
    total = total_through(lesson_id)
    checklist = rel(lesson_dir, CHECKLIST_DIR + "/README.md")

    lines = ["## LeetCode 150 you can now solve", "", NOTE, ""]
    if new:
        word = "problem" if len(new) == 1 else "problems"
        lines.append(f"This lesson unlocks **{len(new)}** Top Interview 150 {word}. "
                     f"Running total: **{total} / 150**.")
    else:
        lines.append(f"No new Top Interview 150 problems in this lesson. It builds the tools the next ones need. "
                     f"Running total: **{total} / 150**.")
    if new:
        lines.append(f"Date each one in the [Section 24 checklist]({checklist}) when you try it and when you solve it.")
    else:
        lines.append(f"See the full path in the [Section 24 checklist]({checklist}).")
    lines.append("")

    if labs:
        lines += ["**Labs** (built here, with tests, hints, and a solution):", "",
                  "| # | Problem | Diff | Lab |", "|---|---|---|---|"]
        for n in labs:
            path = L.LABS[n][0][1]
            lines.append(f"| {n} | {link(n)} | {P[n][3]} | [{os.path.basename(path)}]({rel(lesson_dir, path)}) |")
        lines.append("")
        lines.append("Pass the lab here first. Then submit the same code on LeetCode to confirm it.")
        lines.append("")

    if revisit:
        lines += ["**Revisit** (a problem you already unlocked, solved a better way):", "",
                  "| # | Problem | Diff | Lab |", "|---|---|---|---|"]
        for n, path in revisit:
            lines.append(f"| {n} | {link(n)} | {P[n][3]} | [{os.path.basename(path)}]({rel(lesson_dir, path)}) |")
        lines.append("")

    if early:
        lines += ["**Early unlocks** (from a later section, but this lesson gave you enough to solve them now). "
                  "Solve them on LeetCode. The full lab, hints, and solution come in the home section.", "",
                  "| # | Problem | Diff | Home | Nudge |", "|---|---|---|---|---|"]
        for n in early:
            home = P[n][4]
            lines.append(f"| {n} | {link(n)} | {P[n][3]} | {home} {L.SECTION_NAMES[home]} | {L.EARLY[n][1]} |")
        lines.append("")
        lines.append("Stuck for 20 minutes on an early unlock? Stop. Note it in the checklist and move on. "
                     "Its home section will teach the rest.")
        lines.append("")

    if not new and next_stamp:
        k = len(unlocked_by(next_stamp))
        lines.append(f"Next unlock: **{stamp_label(next_stamp)}** ({k} problem{'s' if k != 1 else ''}).")
    return "\n".join(lines)


# ---------------------------------------------------------------- section README blocks

def section_block(sec, readme_dir):
    stamps = [s for s in all_stamps() if section_of(s) == sec and "." in s]
    rows = []
    for s in stamps:
        for n in unlocked_by(s):
            if n in L.LABS and n not in L.EARLY:
                path = L.LABS[n][0][1]
                where = f"Lab: [{os.path.basename(path)}]({rel(readme_dir, path)})"
                kind = "Lab"
            else:
                home = P[n][4]
                where = f"LeetCode now · full lab in {home} {L.SECTION_NAMES[home]}"
                kind = "Early"
            rows.append(f"| {s} | {n} | {link(n)} | {P[n][3]} | {kind} | {where} |")
    for s in stamps:
        for n, path in revisits_in(s):
            rows.append(f"| {s} | {n} | {link(n)} | {P[n][3]} | Revisit | "
                        f"Lab: [{os.path.basename(path)}]({rel(readme_dir, path)}) |")

    new = sum(len(unlocked_by(s)) for s in stamps)
    last = stamps[-1] if stamps else None
    after = total_through(last) if last else total_through(sec)
    checklist = rel(readme_dir, CHECKLIST_DIR + "/README.md")
    lines = ["## LeetCode 150 in this section", "", NOTE, "",
             f"This section unlocks **{new}** of the Top Interview 150. "
             f"When you finish it you can attempt **{after} / 150**.",
             "Every lesson ends with the problems it unlocks. "
             f"The full list, with date columns, is the [Section 24 checklist]({checklist}).", "",
             "- **Lab**: built in this course. Pass the tests here, then submit on LeetCode.",
             "- **Early**: from a later section. Solve it on LeetCode now with what you know. "
             "The lab comes in its home section.",
             "- **Revisit**: a problem you already unlocked, solved a better way.", "",
             "| Lesson | # | Problem | Diff | Type | Where |", "|---|---|---|---|---|---|"]
    lines += rows
    return "\n".join(lines)


# ---------------------------------------------------------------- main README block

def main_readme_block():
    built = list(L.SECTION_DIRS)
    rows = ["| After section | Unlocked | Of 150 |", "|---|---|---|"]
    for sec in built:
        stamps = [s for s in all_stamps() if section_of(s) == sec]
        last = stamps[-1] if stamps else sec
        rows.append(f"| {sec} {L.SECTION_NAMES[sec]} | {sum(len(unlocked_by(s)) for s in stamps)} | "
                    f"{total_through(last)} |")
    return "\n".join([
        "## The LeetCode 150 path", "", NOTE, "",
        "This course teaches Python so you can solve the "
        "[LeetCode Top Interview 150](https://leetcode.com/studyplan/top-interview-150/) and pass coding rounds.",
        "The moment a lesson teaches what a Top 150 problem needs, that problem appears at the end of the lesson.",
        "Some come with a full lab. Some are **early unlocks** from later sections: you solve them on LeetCode now,",
        "and the full lab arrives in their home section. By the end of Section 23, all 150 are unlocked.", "",
        f"Track every one in the **[Section 24 checklist]({CHECKLIST_DIR}/README.md)**: "
        "the lesson that unlocks it, plus blank columns for the date you tried it and the date you solved it.", "",
    ] + rows)


# ---------------------------------------------------------------- Section 24

def checklist_readme():
    lines = [
        "# 24 · LeetCode Top Interview 150 Checklist", "",
        "*Generated by `tools/build_unlocks.py` from `tools/leetcode150.py`. "
        "Rebuilding keeps your Tried and Solved dates.*", "",
        "All 150 problems from the [LeetCode Top Interview 150](https://leetcode.com/studyplan/top-interview-150/), "
        "in the order this course unlocks them.", "",
        "**Unlocked by** is your stamp. Once you finish that lesson (or section), you have learned what the problem "
        "needs. Try it.", "",
        "## How to use it", "",
        "1. Finish a lesson. Its last block lists what it unlocked. Find those rows here.",
        "2. Try each one. Write the date in **Tried**.",
        "3. Solve it and pass LeetCode's tests. Write the date in **Solved**. "
        "Needed a hint or the solution? Write `H` or `S` after the date, and try it again in a week.",
        "4. Lab rows: pass the course lab first, then submit on LeetCode.",
        "5. Early rows: the course has no lab for it yet. Solve it on LeetCode. "
        "Stuck after 20 minutes? Note it and move on. Its home section teaches the rest.",
        "6. Repeated a mistake? Log it in [MISTAKES.md](../../MISTAKES.md).", "",
        "Prefer a spreadsheet? Open [checklist.csv](checklist.csv) in Excel or Google Sheets.", "",
        "**Where** key: `Lab` = a lab in this course · `Early` = solve on LeetCode now, full lab later · "
        "`Section NN` = taught when that section is built.", "",
    ]

    # Summary
    lines += ["## Progress at a glance", "", "| Unlocked by | New | Running total |", "|---|---|---|"]
    glance = sorted(set(all_stamps()) | {f"{i:02d}" for i in range(5, 24)}, key=L.lesson_order)
    for s in glance:
        k = len(unlocked_by(s))
        extra = "" if k or "." in s else " (all unlocked early; this section adds the labs)"
        lines.append(f"| {stamp_label(s)}{extra} | {k} | {total_through(s)} / 150 |")
    lines.append("")

    # Main table, grouped by stamp
    lines += ["## The checklist (unlock order)", ""]
    for s in all_stamps():
        nums = unlocked_by(s)
        sec = section_of(s)
        lines.append(f"### {stamp_label(s)}  ·  {len(nums)} new  ·  {total_through(s)} / 150")
        lines.append("")
        lines.append("| ✓ | # | Problem | Diff | Category | Where | Tried | Solved |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for n in nums:
            p = P[n]
            if n in L.LABS and n not in L.EARLY:
                path = L.LABS[n][0][1]
                where = f"Lab: [{os.path.basename(path).replace('.py', '')}]({rel(os.path.join(ROOT, CHECKLIST_DIR), path)})"
            elif n in L.EARLY and n in L.LABS:
                path = L.LABS[n][0][1]
                where = f"Early · lab: [{os.path.basename(path).replace('.py', '')}]({rel(os.path.join(ROOT, CHECKLIST_DIR), path)})"
            elif n in L.EARLY:
                where = f"Early (lab in {p[4]})"
            else:
                where = f"Section {sec}"
            lines.append(f"| ☐ | {n} | {link(n)} | {p[3]} | {p[4]} {L.SECTION_NAMES[p[4]]} | {where} |  |  |")
        lines.append("")

    # By category
    lines += ["## By category (the official Top 150 groups)", "",
              "The same 150, grouped the way LeetCode groups them. Each problem shows its unlock stamp.", "",
              "| Section | Category | Count | Problems (unlocked by) |", "|---|---|---|---|"]
    cats = {}
    for p in L.PROBLEMS:
        cats.setdefault(p[4], []).append(p[0])
    for sec in sorted(cats):
        items = ", ".join(f"{n} ({L.unlock_of(n)})" for n in cats[sec])
        lines.append(f"| {sec} | {L.SECTION_NAMES[sec]} | {len(cats[sec])} | {items} |")
    lines += ["", f"**Total: {len(L.PROBLEMS)} problems.**", "",
              "## When a new section is built", "",
              "Add its labs to `LABS` in `tools/leetcode150.py` (and any new early unlocks to `EARLY`), then run "
              "`python tools/build_unlocks.py`. The stamps here update. Your dates do not: "
              "the builder keeps anything you typed in the Tried and Solved columns.", ""]
    return "\n".join(lines)


def keep_dates(new_text, old_text):
    """Carry the user's Tried/Solved dates and ✓ marks from the old checklist into the new one."""
    if not old_text:
        return new_text
    saved = {}
    for line in old_text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 8 and cells[1].isdigit():
            saved[cells[1]] = (cells[0], cells[6], cells[7])
    out = []
    for line in new_text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 8 and cells[1].isdigit() and cells[1] in saved:
            mark, tried, solved = saved[cells[1]]
            cells[0], cells[6], cells[7] = mark or "☐", tried, solved
            line = "| " + " | ".join(cells[:6]) + f" | {cells[6]} | {cells[7]} |"
        out.append(line)
    return "\n".join(out) + ("\n" if new_text.endswith("\n") else "")


def checklist_csv(old_csv):
    saved = {}
    if old_csv:
        for row in csv.DictReader(io.StringIO(old_csv)):
            saved[row.get("number", "")] = (row.get("tried", ""), row.get("solved", ""))
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["order", "unlocked_by", "number", "title", "difficulty", "category", "where", "url",
                "tried", "solved"])
    i = 0
    for s in all_stamps():
        for n in unlocked_by(s):
            i += 1
            p = P[n]
            where = "Early" if n in L.EARLY else ("Lab" if n in L.LABS else f"Section {section_of(s)}")
            tried, solved = saved.get(str(n), ("", ""))
            w.writerow([i, stamp_label(s), n, p[1], DIFF[p[3]], f"{p[4]} {L.SECTION_NAMES[p[4]]}", where,
                        L.url(p[2]), tried, solved])
    return buf.getvalue()


# ---------------------------------------------------------------- driver

def read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return ""


def main():
    check_only = "--check" in sys.argv
    L.check()
    outputs = {}

    lessons = lesson_files()
    stamps = all_stamps()
    for lesson_id, _sec, path in lessons:
        later = [s for s in stamps if L.lesson_order(s) > L.lesson_order(lesson_id)]
        block = lesson_block(lesson_id, os.path.dirname(path), later[0] if later else None)
        outputs[path] = replace_block(read(path), block)

    for sec, d in L.SECTION_DIRS.items():
        path = os.path.join(ROOT, "sections", d, "README.md")
        outputs[path] = replace_block(read(path), section_block(sec, os.path.dirname(path)),
                                      before_heading="## Mastery gate")

    path = os.path.join(ROOT, "README.md")
    outputs[path] = replace_block(read(path), main_readme_block(), before_heading="## Cumulative review")

    cdir = os.path.join(ROOT, CHECKLIST_DIR)
    rpath = os.path.join(cdir, "README.md")
    outputs[rpath] = keep_dates(checklist_readme(), read(rpath))
    cpath = os.path.join(cdir, "checklist.csv")
    outputs[cpath] = checklist_csv(read(cpath))

    stale = [p for p, text in outputs.items() if read(p) != text]
    if check_only:
        for p in stale:
            print("out of date:", os.path.relpath(p, ROOT))
        sys.exit(1 if stale else 0)

    os.makedirs(cdir, exist_ok=True)
    for p in stale:
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(outputs[p])
        print("wrote", os.path.relpath(p, ROOT))
    total = total_through(stamps[[i for i, s in enumerate(stamps) if section_of(s) in L.SECTION_DIRS][-1]])
    print(f"{len(lessons)} lessons, {len(L.SECTION_DIRS)} sections. "
          f"Unlocked by the end of the built sections: {total} / 150.")


if __name__ == "__main__":
    main()
